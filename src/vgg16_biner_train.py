"""## 3. Helper Functions"""

def make_generators(train_dir, val_dir, batch_size):
    train_datagen = ImageDataGenerator(
        preprocessing_function=vgg_preprocess,
        width_shift_range=0.1,
        zoom_range=0.05,
        brightness_range=[0.9, 1.1],
    )
    val_datagen = ImageDataGenerator(preprocessing_function=vgg_preprocess)

    train_gen = train_datagen.flow_from_directory(
        train_dir, target_size=IMG_SIZE, batch_size=batch_size,
        class_mode='categorical', shuffle=True, seed=SEED
    )
    val_gen = val_datagen.flow_from_directory(
        val_dir, target_size=IMG_SIZE, batch_size=batch_size,
        class_mode='categorical', shuffle=False
    )
    return train_gen, val_gen


def get_class_weights(train_gen):
    labels  = train_gen.classes
    weights = compute_class_weight('balanced', classes=np.unique(labels), y=labels)
    return dict(enumerate(weights))


def build_vgg16():
    base = VGG16(weights='imagenet', include_top=False, input_shape=IMG_SHAPE)
    base.trainable = False
    x   = base.output
    x   = layers.GlobalAveragePooling2D()(x)
    x   = layers.BatchNormalization()(x)
    x   = layers.Dense(CFG['dense_units_1'], activation='relu',
                       kernel_regularizer=regularizers.l2(CFG['l2']))(x)
    x   = layers.Dropout(CFG['dropout_1'])(x)
    x   = layers.Dense(CFG['dense_units_2'], activation='relu',
                       kernel_regularizer=regularizers.l2(CFG['l2']))(x)
    x   = layers.Dropout(CFG['dropout_2'])(x)
    out = layers.Dense(NUM_CLASSES, activation='softmax')(x)
    return models.Model(inputs=base.input, outputs=out), base


def compile_model(model, lr):
    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=lr),
        loss='categorical_crossentropy',
        metrics=['accuracy',
                 tf.keras.metrics.Precision(name='precision'),
                 tf.keras.metrics.Recall(name='recall'),
                 tf.keras.metrics.AUC(name='auc')]
    )


def make_callbacks(name):
    return [
        EarlyStopping(monitor='val_accuracy', patience=CFG['patience_stop'],
                      restore_best_weights=True, verbose=1),
        ReduceLROnPlateau(monitor='val_loss', factor=0.5,
                          patience=CFG['patience_lr'], min_lr=1e-7, verbose=1),
        ModelCheckpoint(os.path.join(SAVE_DIR, f'best_{name}.keras'),
                        monitor='val_accuracy', save_best_only=True, verbose=0),
    ]

