def evaluate_model(model, history, val_gen, phase):
    class_names = list(val_gen.class_indices.keys())
    phase_label = 'Phase 1 — Frozen Base' if phase == 'frozen' else 'Phase 2 — Fine-tuning'

    # Training curves
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))
    fig.suptitle(f'VGG16 | STFT | E2 | {phase_label}', fontweight='bold')
    for ax, (tk, vk), metric in zip(axes,
        [('accuracy', 'val_accuracy'), ('loss', 'val_loss')],
        ['Accuracy', 'Loss']):
        ax.plot(history.history[tk], label='Train', color='steelblue',    lw=1.5)
        ax.plot(history.history[vk], label='Validation', color='darkorange', lw=1.5)
        ax.set_xlabel('Epoch')
        ax.set_ylabel(metric)
        ax.set_title(metric)
        ax.legend()
        ax.grid(True, alpha=0.3)
        ax.spines[['top', 'right']].set_visible(False)
    plt.tight_layout()
    plt.savefig(os.path.join(SAVE_DIR, f'history_vgg16_{phase}.png'))
    plt.show()

    val_gen.reset()
    y_pred_prob = model.predict(val_gen, verbose=0)
    y_pred      = np.argmax(y_pred_prob, axis=1)
    y_true      = val_gen.classes

    # Confusion matrix
    cm     = confusion_matrix(y_true, y_pred)
    labels = [c.capitalize() for c in class_names]
    fig, ax = plt.subplots(figsize=(5, 4))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
                xticklabels=labels, yticklabels=labels,
                linewidths=0.5, ax=ax)
    ax.set_title(f'Confusion Matrix — VGG16 ({phase_label})', pad=12)
    ax.set_ylabel('True Label')
    ax.set_xlabel('Predicted Label')
    plt.tight_layout()
    plt.savefig(os.path.join(SAVE_DIR, f'cm_vgg16_{phase}.png'))
    plt.show()

    # ROC curve
    fpr, tpr, _ = roc_curve(y_true, y_pred_prob[:, 1])
    roc_auc     = auc(fpr, tpr)
    fig, ax = plt.subplots(figsize=(6, 5))
    ax.plot(fpr, tpr, color='darkorange', lw=2, label=f'AUC = {roc_auc:.4f}')
    ax.plot([0, 1], [0, 1], color='navy', lw=1, linestyle='--', label='Random Classifier')
    ax.set_xlabel('False Positive Rate')
    ax.set_ylabel('True Positive Rate')
    ax.set_title(f'ROC Curve — VGG16 ({phase_label})', pad=12)
    ax.legend(loc='lower right')
    ax.grid(True, alpha=0.3)
    ax.spines[['top', 'right']].set_visible(False)
    plt.tight_layout()
    plt.savefig(os.path.join(SAVE_DIR, f'roc_vgg16_{phase}.png'))
    plt.show()

    tn, fp, fn, tp = cm.ravel()
    acc       = accuracy_score(y_true, y_pred)
    precision = tp / (tp + fp + 1e-10)
    recall    = tp / (tp + fn + 1e-10)
    f1        = 2 * precision * recall / (precision + recall + 1e-10)
    best_ep   = int(np.argmax(history.history['val_accuracy'])) + 1

    print(classification_report(y_true, y_pred, target_names=labels, digits=4))
    print(f'Accuracy   : {acc*100:.2f}%')
    print(f'Recall     : {recall*100:.2f}%')
    print(f'F1-Score   : {f1*100:.2f}%')
    print(f'AUC-ROC    : {roc_auc*100:.2f}%')
    print(f'Best Epoch : {best_ep}')
    print(f'TP={tp} | TN={tn} | FP={fp} | FN={fn}')

    return {'acc': acc, 'recall': recall, 'f1': f1, 'auc': roc_auc,
            'tp': tp, 'tn': tn, 'fp': fp, 'fn': fn}

