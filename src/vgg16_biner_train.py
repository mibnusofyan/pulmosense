"""### GradCAM + Waveform Overlay"""

def get_gradcam_heatmap(model, img_array, last_conv_layer_name, pred_index=None):
    grad_model = tf.keras.models.Model(
        inputs  = model.inputs,
        outputs = [model.get_layer(last_conv_layer_name).output, model.output]
    )
    with tf.GradientTape() as tape:
        conv_outputs, predictions = grad_model(img_array)
        if pred_index is None:
            pred_index = tf.argmax(predictions[0])
        class_channel = predictions[:, pred_index]

    grads   = tape.gradient(class_channel, conv_outputs)
    pooled  = tf.reduce_mean(grads, axis=(0, 1, 2))
    heatmap = conv_outputs[0] @ pooled[..., tf.newaxis]
    heatmap = tf.squeeze(heatmap)
    heatmap = tf.maximum(heatmap, 0) / (tf.math.reduce_max(heatmap) + 1e-8)
    return heatmap.numpy()


def visualize_gradcam_with_waveform(model, img_path, wav_path, class_names,
                                     last_conv='block5_conv3', save_dir=SAVE_DIR):
    img       = load_img(img_path, target_size=(224, 224))
    img_array = img_to_array(img)
    img_input = np.expand_dims(vgg_preprocess(img_array.copy()), axis=0)

    preds      = model.predict(img_input, verbose=0)
    pred_idx   = np.argmax(preds[0])
    confidence = preds[0][pred_idx] * 100
    label      = class_names[pred_idx].upper()

    heatmap   = get_gradcam_heatmap(model, img_input, last_conv, pred_idx)
    img_bgr   = cv2.resize(cv2.imread(img_path), (224, 224))
    img_rgb   = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
    heatmap_r = cv2.resize(heatmap, (224, 224))
    heat_rgb  = cv2.cvtColor(cv2.applyColorMap(np.uint8(255 * heatmap_r), cv2.COLORMAP_JET), cv2.COLOR_BGR2RGB)
    overlay   = (img_rgb * 0.6 + heat_rgb * 0.4).astype(np.uint8)

    # Overlay waveform on top of GradCAM overlay
    audio           = load_and_preprocess_audio(wav_path)
    n_frames        = overlay.shape[1]
    audio_resampled = np.interp(np.linspace(0, len(audio)-1, n_frames),
                                np.arange(len(audio)), audio)
    waveform_norm = (audio_resampled - audio_resampled.min()) / (audio_resampled.max() - audio_resampled.min() + 1e-9)
    waveform_px   = (10 + waveform_norm * (overlay.shape[0] - 20)).astype(int)

    overlay_with_wave = overlay.copy()
    for x in range(1, n_frames):
        cv2.line(overlay_with_wave,
                 (x-1, waveform_px[x-1]),
                 (x,   waveform_px[x]),
                 (255, 230, 0), 2)

    # Identify focus frequency range
    heatmap_norm = heatmap_r / (heatmap_r.max() + 1e-8)
    hot_rows     = np.where(heatmap_norm > 0.6)
    if len(hot_rows[0]) > 0:
        row_mean   = np.mean(hot_rows[0])
        freq_focus = HIGH_CUT - (row_mean / 224) * (HIGH_CUT - LOW_CUT)
        freq_lo    = max(LOW_CUT,  freq_focus - 150)
        freq_hi    = min(HIGH_CUT, freq_focus + 150)
        caption    = f'Model attention concentrated at {freq_lo:.0f}–{freq_hi:.0f} Hz'
    else:
        caption = 'Model attention distributed across the full spectrum'

    freq_ticks  = np.linspace(LOW_CUT, HIGH_CUT, 6)
    pixel_ticks = [(HIGH_CUT - f) / (HIGH_CUT - LOW_CUT) * 224 for f in freq_ticks]
    title_color = '#c62828' if label == 'PNEUMONIA' else '#2e7d32'

    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    fig.suptitle(f'Spectral Analysis — Prediction: {label} ({confidence:.1f}%)',
                 fontweight='bold', color=title_color)

    panel_titles = ['STFT Spectrogram', 'GradCAM Heatmap', 'Overlay + Raw Waveform']
    for ax, img_data, title in zip(axes, [img_rgb, heat_rgb, overlay_with_wave], panel_titles):
        ax.imshow(img_data)
        ax.set_title(title)
        ax.set_yticks(pixel_ticks)
        ax.set_yticklabels([f'{f:.0f} Hz' for f in freq_ticks])
        ax.set_xlabel('Time Frame')
        ax.set_ylabel('Frequency (Hz)')

    sm   = plt.cm.ScalarMappable(cmap='jet', norm=plt.Normalize(0, 1))
    sm.set_array([])
    cbar = plt.colorbar(sm, ax=axes[1], fraction=0.046, pad=0.04)
    cbar.set_label('Contribution to Prediction')
    cbar.set_ticks([0, 0.5, 1])
