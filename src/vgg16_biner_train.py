def get_confidence_label(confidence, label):
    is_pneumonia = label.upper() == 'PNEUMONIA'
    if confidence >= 85:
        return 'High confidence. Immediate clinical follow-up is recommended.' if is_pneumonia else 'No indication of pneumonia detected.'
    elif confidence >= 65:
        return 'Moderate confidence. Consider additional examination.' if is_pneumonia else 'No pneumonia detected. Moderate confidence.'
    else:
        return 'Low confidence. Please re-record audio or perform manual examination.'

"""### Audio Preprocessing"""

def load_and_preprocess_audio(wav_path):
    audio, sr = librosa.load(wav_path, sr=None, mono=True)
    if sr != TARGET_SR:
        audio = librosa.resample(audio, orig_sr=sr, target_sr=TARGET_SR)
    audio -= np.mean(audio)
    nyq   = TARGET_SR / 2.0
    sos   = signal.butter(4, [LOW_CUT/nyq, HIGH_CUT/nyq], btype='band', output='sos')
    audio = signal.sosfiltfilt(sos, audio)
    audio /= (np.max(np.abs(audio)) + 1e-9)
    target_len = int(DURASI * TARGET_SR)
    if len(audio) < target_len:
        audio = np.pad(audio, (0, target_len - len(audio)), mode='reflect')
    else:
        audio = audio[:target_len]
    return audio

