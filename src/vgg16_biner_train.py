"""### Power Spectral Density Comparison"""

def compute_mean_psd_per_class(val_wav_dir, n_samples=30):
    mean_psds = {}
    for cls, folder in val_wav_dir.items():
        files = [f for f in os.listdir(folder) if f.endswith('.wav')][:n_samples]
        psds  = []
        for f in files:
            try:
                audio      = load_and_preprocess_audio(os.path.join(folder, f))
                freqs, psd = signal.welch(audio, fs=TARGET_SR, nperseg=256)
                mask       = (freqs >= LOW_CUT) & (freqs <= HIGH_CUT)
                psds.append(10 * np.log10(psd[mask] + 1e-10))
            except Exception:
                pass
        if psds:
            mean_psds[cls] = {'freqs': freqs[mask], 'psd': np.mean(psds, axis=0)}
    return mean_psds


