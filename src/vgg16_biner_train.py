    axes[2].legend(loc='lower right', framealpha=0.6)

    fig.text(0.5, -0.02, caption, ha='center', fontsize=10, style='italic', color='#333333',
             bbox=dict(boxstyle='round,pad=0.5', facecolor='#fff9e6', edgecolor='#f0c040'))

